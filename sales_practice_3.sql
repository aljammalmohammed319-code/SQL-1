DROP DATABASE IF EXISTS sales_practice3;
CREATE DATABASE sales_practice3 CHARACTER SET utf8mb4;

-- Text columns that matter use the case-sensitive collation
-- utf8mb4_bin, so 'Amman' and 'amman' are different values.
USE sales_practice3;

CREATE TABLE customers (
  customer_id   INT,
  customer_name VARCHAR(60) COLLATE utf8mb4_bin,
  email         VARCHAR(80) COLLATE utf8mb4_bin,
  city          VARCHAR(30) COLLATE utf8mb4_bin,
  segment       VARCHAR(20),
  signup_date   DATE
);

CREATE TABLE products (
  product_id   INT,
  product_name VARCHAR(40),
  category     VARCHAR(30) COLLATE utf8mb4_bin,
  unit_price   VARCHAR(20),
  cost         DECIMAL(10,2)
);

CREATE TABLE employees (
  employee_id   INT,
  employee_name VARCHAR(40),
  region        VARCHAR(20),
  manager_id    INT,
  hire_date     DATE
);

CREATE TABLE orders (
  order_id       INT,
  order_date     VARCHAR(15),
  customer_id    INT,
  employee_id    INT,
  status         VARCHAR(20) COLLATE utf8mb4_bin,
  ship_date      DATE,
  payment_method VARCHAR(20)
);

CREATE TABLE order_items (
  item_id      INT,
  order_id     INT,
  product_id   INT,
  quantity     INT,
  discount_pct DECIMAL(5,2)
);

CREATE TABLE data_issues (
  issue_id      INT,
  level         VARCHAR(10),
  table_name    VARCHAR(30),
  column_name   VARCHAR(40),
  problem       VARCHAR(255),
  how_to_find   VARCHAR(255),
  rows_affected INT
);

